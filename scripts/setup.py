def prompt_input(label: str, default: str = "") -> str:
    val = input(f"{label} [{default}]: ").strip() if default else input(f"{label}: ").strip()
    return val or default


def prompt_choice(label: str, options: dict[str, tuple[str, str]]) -> str:
    print()
    for key, (value, desc) in options.items():
        print(f"  [{key}] {desc}")
    print()
    while True:
        choice = input(f"{label} (1-{len(options)}): ").strip()
        if choice in options:
            return options[choice][0]


def prompt_bool(label: str, default: bool = False) -> bool:
    d = "Y/n" if default else "y/N"
    ans = input(f"{label} [{d}]: ").strip().lower()
    if not ans:
        return default
    return ans in ("y", "yes", "true")


