# ── LLM validation ──────────────────────────────────────────────────────────


def validate_llm(config: dict) -> bool:
    import httpx

    print("\n  Testing LLM connection...")
    url = f"{config['LLM_BASE_URL'].rstrip('/')}/chat/completions"
    try:
        with httpx.Client(timeout=10.0) as client:
            resp = client.post(
                url,
                headers={
                    "Authorization": f"Bearer {config['LLM_API_KEY']}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": config["LLM_MODEL"],
                    "messages": [{"role": "user", "content": "Say hi"}],
                    "max_tokens": 5,
                },
            )
            if resp.status_code == 200:
                print("  ✅ LLM connection successful!")
                return True
            print(f"  HTTP {resp.status_code}: {resp.text[:200]}")
            return False
    except httpx.ConnectError:
        print("  Cannot connect. Check your base URL.")
        return False
    except Exception as e:
        print(f"  Connection failed: {e}")
        return False


# ── VAPID key generation ────────────────────────────────────────────────────


def generate_vapid_keys() -> tuple[str, str]:
    """Generate VAPID key pair using cryptography."""
    from cryptography.hazmat.primitives.asymmetric.ec import generate_private_key, SECP256R1
    from cryptography.hazmat.primitives import serialization

    private_key = generate_private_key(SECP256R1())
    public_key = private_key.public_key()

    priv_bytes = private_key.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )
    pub_bytes = public_key.public_bytes(
        encoding=serialization.Encoding.X962,
        format=serialization.PublicFormat.UncompressedPoint,
    )

    return (
        base64.urlsafe_b64encode(pub_bytes).decode().rstrip("="),
        base64.urlsafe_b64encode(priv_bytes).decode().rstrip("="),
    )


