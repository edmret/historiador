# ── Interactive wizard ──────────────────────────────────────────────────────


def wizard_interactive():
    config = dict(DEFAULTS)
    banner()

    # ── 1. LLM ──
    section("1. LLM Provider Configuration")
    print("  Any OpenAI-compatible API works (OpenAI, OpenRouter, nan.builders, etc.)\n")

    config["LLM_BASE_URL"] = prompt_input("  Base URL", DEFAULTS["LLM_BASE_URL"])
    config["LLM_API_KEY"] = prompt_input("  API Key")
    if not config["LLM_API_KEY"]:
        print("  Warning: no API key — the app won't generate histories.")
        if not prompt_bool("  Continue anyway?", default=True):
            print("  Aborted.")
            sys.exit(1)

    # Model
    print()
    for i, m in enumerate(LLM_MODELS, 1):
        tag = "  (default)" if m == DEFAULTS["LLM_MODEL"] else ""
        print(f"  [{i}] {m}{tag}")
    print("  [7] custom\n")
    while True:
        choice = input(f"  Model (1-7) [1]: ").strip() or "1"
        if choice == "7":
            config["LLM_MODEL"] = prompt_input("  Model name", "")
            break
        if choice.isdigit() and 1 <= int(choice) <= len(LLM_MODELS):
            config["LLM_MODEL"] = LLM_MODELS[int(choice) - 1]
            break

    # Test
    if config["LLM_API_KEY"]:
        if not validate_llm(config):
            prompt_bool("  Retry?", default=False)

    # ── 2. Search ──
    section("2. Web Search Configuration")
    print("  DuckDuckGo is free and requires no API key.\n")
    config["SEARCH_PROVIDER"] = prompt_choice("  Provider", SEARCH_PROVIDERS)

    if config["SEARCH_PROVIDER"] == "tavily":
        config["TAVILY_API_KEY"] = prompt_input("  Tavily API Key")
    elif config["SEARCH_PROVIDER"] == "serpapi":
        config["SERPAPI_API_KEY"] = prompt_input("  SerpAPI Key")
    elif config["SEARCH_PROVIDER"] == "hermes":
        config["HERMES_PATH"] = prompt_input("  Hermes path", DEFAULTS["HERMES_PATH"])

    # ── 3. Database ──
    section("3. Database Configuration")
    print("  SQLite — no external DB needed.\n")
    config["DATABASE_URL"] = prompt_input("  Database URL", DEFAULTS["DATABASE_URL"])

    # ── 4. Push notifications ──
    section("4. Web Push Notifications (optional)")
    print("  Alerts users when histories are ready. Can be added later.\n")
    if prompt_bool("  Generate VAPID keys now?", default=False):
        try:
            pub, priv = generate_vapid_keys()
            config["VAPID_PUBLIC_KEY"] = pub
            config["VAPID_PRIVATE_KEY"] = priv
            print("  VAPID keys generated")
        except Exception as e:
            print(f"  VAPID generation failed: {e}")
    config["VAPID_CLAIM_EMAIL"] = prompt_input(
        "  Claim email", DEFAULTS["VAPID_CLAIM_EMAIL"]
    )

    # ── 5. App settings ──
    section("5. App Settings")
    config["DEFAULT_NUM_HISTORIES"] = prompt_input(
        "  Histories per topic", DEFAULTS["DEFAULT_NUM_HISTORIES"]
    )
    config["DEFAULT_NUM_RESEARCH_AGENTS"] = prompt_input(
        "  Parallel research agents", DEFAULTS["DEFAULT_NUM_RESEARCH_AGENTS"]
    )
    config["MAX_SCOPING_ROUNDS"] = prompt_input(
        "  Max scoping rounds", DEFAULTS["MAX_SCOPING_ROUNDS"]
    )
    config["MAX_QUERIES_PER_AGENT"] = prompt_input(
        "  Max queries per agent", DEFAULTS["MAX_QUERIES_PER_AGENT"]
    )
    config["MAX_PAGES_PER_QUERY"] = prompt_input(
        "  Max pages per query", DEFAULTS["MAX_PAGES_PER_QUERY"]
    )

    # ── 6. Summary ──
    section("6. Summary")
    print()
    print(f"    Model:        {config['LLM_MODEL']}")
    print(f"    Base URL:     {config['LLM_BASE_URL']}")
    api = config["LLM_API_KEY"]
    print(f"    API Key:      {'***' + api[-4:] if api else '(not set)'}")
    print(f"    Search:       {config['SEARCH_PROVIDER']}")
    print(f"    Database:     {config['DATABASE_URL']}")
    print(f"    Push:         {'configured' if config['VAPID_PUBLIC_KEY'] else 'skipped'}")
    print()

    if prompt_bool("  Write .env file?", default=True):
        write_env(config)

    # ── 7. DB init ──
    section("7. Initialize Database")
    init_database()

    # Done
    print()
    print("╔══════════════════════════════════════════════════════════╗")
    print("║  Setup complete!                                        ║")
    print("║                                                        ║")
    print("║  Start:   bash scripts/run.sh                          ║")
    print("║  Or:      uvicorn backend.main:app --port 8080         ║")
    print("║                                                        ║")
    print("║  Open:    http://localhost:8080                         ║")
    print("╚══════════════════════════════════════════════════════════╝")
    print()


