"""SQLAlchemy 2.0 typed ORM for Historiador.

Design notes (the *why*, since the *what* is readable from the code):

* **Typed `Mapped[...]` style only.** The legacy ``backend/models`` used untyped
  ``Column()``, which meant nullability and Python types were invisible to mypy and
  every read site had to guess. Here ``Mapped[str]`` vs ``Mapped[str | None]`` is the
  single source of truth for both the DDL and the type checker.

* **Constraints are real.** The legacy schema had foreign keys with no ``ON DELETE``
  behaviour, no ``NOT NULL`` on fields the app always sets, and free-form ``str``
  status columns guarded only by a comment. That is how ``Topic.status`` shipped with
  a default of ``"scoring"`` — a typo for ``"scoping"`` that no test or constraint
  could catch. Every status column here is a :class:`enum.StrEnum` rendered as a
  ``VARCHAR`` plus a ``CHECK ... IN (...)`` constraint, so the same typo is now a
  write-time failure in both Python and SQLite.

* **No timestamp defaults on the columns.** ARCHITECTURE.md §10 forbids wall-clock
  reads outside a ``Clock``. Repositories therefore pass every timestamp in from an
  injected clock; a column-level ``default=datetime.now`` would smuggle an
  untestable clock into the data layer.

* **Two time representations, on purpose.** Product tables (topics, histories, …)
  store timezone-aware ``DATETIME`` because they are rendered to humans and queried
  by date. Observability tables (``runs``, ``run_nodes``, ``events``) store ``REAL``
  epoch seconds because that is what the core runtime's ``Clock`` and ``Event``
  envelope carry (ARCHITECTURE.md §4.1), and round-tripping them through ``datetime``
  would lose sub-millisecond ordering resolution for no benefit.

* **``events.type`` is plain TEXT, not an enum.** The event taxonomy is owned by
  ``core.events.types`` and the data layer must not import ``core`` (ARCHITECTURE.md
  §2 dependency rule). Pinning a CHECK constraint here would force a migration every
  time the runtime learns a new event type — the log must accept whatever the bus
  produced, including types written by a newer daemon.

* **``RunStatus`` / ``NodeState`` mirror the core enums** rather than importing them,
  for the same layering reason. They are the persisted contract; ARCHITECTURE.md §3.2
  is the authority for the values.
"""

from __future__ import annotations

