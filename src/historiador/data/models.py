# ── Naming convention ───────────────────────────────────────────────────────────
# Autogenerated constraint names are what let Alembic drop/alter a constraint later.
# SQLite in particular can only alter a table by rebuilding it, and the rebuild needs
# every constraint to have a stable name. Set this once, on the metadata, so no
# migration ever has to guess a name.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base carrying the shared naming convention."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def new_id() -> str:
    """Fresh row identity.

    UUID4 text rather than an autoincrement integer: ids are minted by the process
    that creates the row (including agents running before a transaction opens) and
    appear in URLs and event payloads, where a guessable sequential id would leak
    volume and ordering.
    """
    return str(uuid.uuid4())


def status_column(enum_cls: type[enum.StrEnum], name: str) -> Enum:
    """Render a :class:`enum.StrEnum` as ``VARCHAR`` + ``CHECK (col IN (...))``.

    ``native_enum=False`` keeps the storage portable (SQLite has no ENUM type) while
    ``create_constraint=True`` still gives the database the power to reject a bad
    value. ``values_callable`` persists the enum *values* (``"scoping"``), not the
    member *names* (``"SCOPING"``), which is what the API and UI speak.
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        length=32,
        create_constraint=True,
        validate_strings=True,
        values_callable=lambda members: [m.value for m in members],
    )


