class Event(Base):
    """The append-only event log — the spine of the product (ARCHITECTURE.md §4).

    The composite primary key ``(run_id, seq)`` is doing three jobs at once:

    1. **Ordering** — the covering index makes ``WHERE run_id = ? AND seq > ?``
       ordered by ``seq`` an index range scan, which is exactly the replay query.
    2. **Gaplessness** — ``seq`` is assigned under a per-run lock by the bus; the PK
       makes a duplicate assignment a hard error instead of a silently reordered UI.
    3. **Idempotency** — a retried batch write can be ``ON CONFLICT DO NOTHING`` on
       this key, so the writer may retry freely without duplicating history.

    Because the PK already covers ``(run_id, seq)``, no extra index is added for the
    plain replay scan — that would be a redundant B-tree on every append. The one
    extra index below serves the dashboard's *filtered* stream (by event type).
    """

    __tablename__ = "events"

    run_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("runs.id", ondelete="CASCADE"), primary_key=True
    )
    seq: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=False)
    ts: Mapped[float] = mapped_column(Float, nullable=False)
    type: Mapped[str] = mapped_column(String(64), nullable=False)
    node_id: Mapped[str | None] = mapped_column(String(128), nullable=True)
    agent: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Per-type payload shape is validated in core.events.types; at rest it is opaque
    # JSON, hence `Any`.
    payload: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)

    __table_args__ = (
        # seq starts at 1 and never skips (ARCHITECTURE.md §4.1). A 0 or negative seq
        # means the bus watermark was reset incorrectly — fail loudly.
        CheckConstraint("seq >= 1", name="event_seq_positive"),
        Index("ix_events_run_id_type_seq", "run_id", "type", "seq"),
    )


