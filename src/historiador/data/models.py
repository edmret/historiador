class Profile(Base):
    """A writing profile: tone, audience and length knobs for the writer agent."""

    __tablename__ = "profiles"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    name: Mapped[str] = mapped_column(String(128), nullable=False, unique=True)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    tone: Mapped[Tone] = mapped_column(
        status_column(Tone, "profile_tone"), nullable=False, default=Tone.NEUTRAL
    )
    audience: Mapped[str] = mapped_column(String(128), nullable=False, default="general")
    preferred_length: Mapped[PreferredLength] = mapped_column(
        status_column(PreferredLength, "profile_length"),
        nullable=False,
        default=PreferredLength.MEDIUM,
    )
    style_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Q&A captured by the profile agent when the profile was created. `Any` is
    # unavoidable: this is user-shaped JSON whose schema belongs to the domain layer.
    creation_feedback: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)


class Topic(Base):
    """A subject the user wants a history about; the root of a generation run."""

    __tablename__ = "topics"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    title: Mapped[str] = mapped_column(String(512), nullable=False)
    status: Mapped[TopicStatus] = mapped_column(
        status_column(TopicStatus, "topic_status"), nullable=False, default=TopicStatus.SCOPING
    )
    # SET NULL, not CASCADE: deleting a writing profile must never delete the user's
    # research. The topic simply falls back to the default profile.
    profile_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("profiles.id", ondelete="SET NULL"), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    __table_args__ = (Index("ix_topics_status_created_at", "status", text("created_at DESC")),)


