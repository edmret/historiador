class ApiToken(Base):
    """A long-lived bearer token for headless/MCP access.

    Only the SHA-256 hex digest is stored. The raw token is shown to the user exactly
    once at creation and is unrecoverable afterwards, so a database leak cannot be
    replayed as authentication. The CHECK constraint pins the column to a 64-character
    digest, which makes accidentally storing a raw ``ht_…`` token a write failure
    rather than a silent, undetectable credential leak.
    """

    __tablename__ = "api_tokens"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    label: Mapped[str] = mapped_column(String(128), nullable=False)
    user_id: Mapped[str] = mapped_column(String(64), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    last_used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)

    __table_args__ = (
        CheckConstraint("length(token_hash) = 64", name="api_token_hash_is_sha256"),
        Index("ix_api_tokens_user_id", "user_id"),
    )


# ── Observability tables ────────────────────────────────────────────────────────


class Run(Base):
    """One execution of the generation DAG.

    ``cost_usd`` is nullable *by design*: ARCHITECTURE.md §5 requires an unknown model
    to yield a cost of ``None``, never a fabricated ``0.0``. A zero here would read as
    "this run was free" on the dashboard, which is a lie; ``NULL`` reads as "unknown".
    """

    __tablename__ = "runs"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    # SET NULL: purging a topic must not erase the audit trail of what the agents did.
    topic_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("topics.id", ondelete="SET NULL"), nullable=True
    )
    status: Mapped[RunStatus] = mapped_column(
        status_column(RunStatus, "run_status"), nullable=False, default=RunStatus.PENDING
    )
    created_at: Mapped[float] = mapped_column(Float, nullable=False)
    started_at: Mapped[float | None] = mapped_column(Float, nullable=True)
    ended_at: Mapped[float | None] = mapped_column(Float, nullable=True)
    prompt_tokens: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    completion_tokens: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    cached_tokens: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    cost_usd: Mapped[float | None] = mapped_column(Float, nullable=True)
    # DAG snapshot ({"nodes": [...], "edges": [...]}) as it was at RUN_CREATED, so the
    # dashboard can draw a historical run without re-deriving the pipeline definition.
    graph: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False, default=dict)
    error: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)

    __table_args__ = (
        CheckConstraint("prompt_tokens >= 0", name="run_prompt_tokens_non_negative"),
        CheckConstraint("completion_tokens >= 0", name="run_completion_tokens_non_negative"),
        CheckConstraint("cached_tokens >= 0", name="run_cached_tokens_non_negative"),
        CheckConstraint("cost_usd IS NULL OR cost_usd >= 0", name="run_cost_non_negative"),
        CheckConstraint(
            "ended_at IS NULL OR started_at IS NOT NULL", name="run_ended_implies_started"
        ),
        # The dashboard's run list is "newest first, optionally filtered by status".
        # This composite index serves both the filtered and unfiltered form.
        Index("ix_runs_status_created_at", "status", text("created_at DESC")),
        Index("ix_runs_topic_id", "topic_id"),
    )


